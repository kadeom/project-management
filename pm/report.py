def _constraint_text(project: Project) -> str:
    """Одна строка со всеми ограничениями и крайними сроками плана для ЛР2."""
    parts = []
    for t in project.leaf_tasks:
        if t.constraint:
            parts.append(f"Ограничение: задача {t.wbs} «{t.name}» — «Начало не ранее» "
                         f"{t.constraint['date']:%d.%m.%Y}.")
        if t.deadline:
            parts.append(f"Крайний срок: веха {t.wbs} «{t.name}» — {t.deadline:%d.%m.%Y}.")
    return " ".join(parts)


def _fix_hint(project: Project, o: dict) -> str:
    """Рекомендуемый способ устранения перегрузки для таблицы ЛР7."""
    if o["peak"] == float("inf"):
        return "Ресурс недоступен (0 %) — перенести задачи или заменить ресурс (Ресурс → Замена ресурсов)"
    if o["peak"] <= 1.5:
        # 1,5 — порог рекомендации, а не расчётная величина: перегрузка до 50 %
        # закрывается сверхурочными в дни пика, выше — уже выравниванием или
        # перераспределением работ.
        return "Сверхурочные в дни пика или выравнивание в пределах резерва"
    return "Выравнивание (задержка задачи с резервом) или перераспределение части работ на другой ресурс"


