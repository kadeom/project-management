def with_shot_ids(B: list[tuple]) -> list[tuple]:
    """("shot", подпись) → ("shot", подпись, "lrN_KK"): устойчивый ID скриншота внутри ЛР.

    Нумерация сбрасывается на каждой ЛР: ID должен совпадать во всех трёх местах —
    analysis.md, .docx и снимках, снятых скриптом на ВМ.
    """
    import re
    lab, k, out = 0, 0, []
    for b in B:
        if b[0] == "h1":
            m = re.match(r"ЛР(\d+)", b[1])
            if m:
                lab, k = int(m[1]), 0
        if b[0] == "shot":
            k += 1
            b = ("shot", b[1], f"lr{lab}_{k:02d}")
        out.append(b)
    return out


def shots(project: Project) -> list[dict]:
    """Метки мест под скриншоты: [{id, caption}] — ID вида lrN_KK для нумерации в отчёте."""
    return [{"id": b[2], "caption": b[1]} for b in blocks(project) if b[0] == "shot"]


